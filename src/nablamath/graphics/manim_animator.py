"""Generate native Manim scenes from audited ODE/integral results and render MP4.

Generated source contains literal data only. It depicts recorded computation,
not a newly invented derivation or an independent proof of the experiment.
"""
import hashlib
from importlib.metadata import version, PackageNotFoundError
import json
import math
from pathlib import Path
import sys
import tempfile

from ..calc.receipt import receipt, verify_receipt
from ..core.semantic_ir import canonical_json
from ..artifacts.process import run_renderer
from .webgl_exporter import _publish_bytes


class ManimAnimator:
    def __init__(self, *, duration=3, max_points=10000):
        if type(duration) not in (int,float) or not math.isfinite(duration) or not .2 <= duration <= 60:
            raise ValueError('Animation duration must be between .2 and 60 seconds')
        if type(max_points) is not int or not 2 <= max_points <= 100000:
            raise ValueError('Invalid trajectory budget')
        self.duration,self.max_points = duration,max_points

    def _story(self, audit_receipt):
        if not verify_receipt(audit_receipt):
            raise ValueError('A valid replayable calculation or device receipt is required')
        if audit_receipt.get('kind') == 'execution_observation':
            if audit_receipt['operation'] not in {'device.ode','device.ode_solve'} or audit_receipt['metadata'].get('capture') != 'values':
                raise ValueError('Animation requires ODE values, not metadata-only observations')
            result = audit_receipt['result']; arguments = audit_receipt['inputs']
            operation = 'ode'
            trajectory = list(zip(result['times'],result['states']))
        else:
            operation = audit_receipt['request']['operation']
            arguments = audit_receipt['request']['arguments']
            result = audit_receipt['result']; trajectory = result.get('trajectory')
        if operation in {'ode','ode_adaptive'}:
            if not isinstance(trajectory,list) or not 2 <= len(trajectory) <= self.max_points:
                raise ValueError('ODE receipt requires a bounded sampled trajectory')
            points = []
            for time,state in trajectory:
                if not isinstance(state,(list,tuple)) or not state or isinstance(state[0],(list,tuple)):
                    raise ValueError('Choose a single ODE trajectory for animation')
                t,y = float(time),float(state[0])
                if not math.isfinite(t) or not math.isfinite(y) or (points and t <= points[-1][0]):
                    raise ValueError('Trajectory requires finite increasing time samples')
                points.append([t,y])
            rate = arguments.get('rate',1)
            law = f"dy/dt = -{rate} y" if arguments.get('model') == 'exponential_decay' else f"d2x/dt2 = -({rate})2 x"
            return {'kind':'ode','title':'Nabla: recorded ODE trajectory','points':points,
                    'steps':[law,f"recorded final value = {points[-1][1]:.8g}"],
                    'hash':audit_receipt['content_id'],'duration':self.duration}
        if operation == 'integrate':
            steps = ['integral of '+arguments['source']]
            if 'antiderivative' in result:
                from ..schema.expression import from_data
                from ..expression import render
                steps.append('antiderivative = '+render(from_data(result['antiderivative'])))
            elif 'value' in result:
                steps.append(f"bounds: {arguments['start']} to {arguments['end']}")
                steps.append('integral value = '+result['value'])
            else:
                raise ValueError('Integral receipt has no renderable result')
            return {'kind':'integral','title':'Nabla: recorded integral','steps':steps,
                    'hash':audit_receipt['content_id'],'duration':self.duration}
        raise ValueError('Only recorded ODE and integral calculations are supported')

    def source(self, audit_receipt):
        story = self._story(audit_receipt)
        data = repr(canonical_json(story))
        return '''# Generated by Nabla; mathematical steps come from the attached receipt.
import json
from manim import Scene, Text, Axes, VMobject, Create, FadeIn, TransformMatchingShapes, UP, DOWN, LEFT, RIGHT, BLUE, config
STORY = json.loads('''+data+''')

class NablaAnimation(Scene):
    def construct(self):
        audit = Text("SHA-256: " + STORY["hash"], font_size=10).to_corner(DOWN+RIGHT)
        title = Text(STORY["title"], font_size=28).to_edge(UP)
        self.add(audit, title)
        if STORY["kind"] == "ode":
            points = STORY["points"]
            low, high = min(p[1] for p in points), max(p[1] for p in points)
            pad = max((high-low)*.15, .1)
            span = points[-1][0]-points[0][0]
            axes = Axes(x_range=[points[0][0],points[-1][0],span/4],
                        y_range=[low-pad,high+pad,(high-low+2*pad)/4],
                        x_length=9,y_length=4,axis_config={"include_numbers":False})
            curve = VMobject(color=BLUE).set_points_as_corners([axes.c2p(t,y) for t,y in points])
            label = Text(STORY["steps"][0],font_size=22).next_to(axes,DOWN)
            self.play(Create(axes),FadeIn(label),run_time=.2)
            self.play(Create(curve),run_time=STORY["duration"])
        else:
            current = Text(STORY["steps"][0],font_size=28)
            if current.width > config.frame_width-1: current.scale_to_fit_width(config.frame_width-1)
            self.play(FadeIn(current),run_time=.2)
            for step in STORY["steps"][1:]:
                following = Text(step,font_size=28)
                if following.width > config.frame_width-1: following.scale_to_fit_width(config.frame_width-1)
                self.play(TransformMatchingShapes(current,following),run_time=STORY["duration"]/max(1,len(STORY["steps"])-1))
                current = following
        self.wait(.2)
'''

    def export_script(self, audit_receipt, destination):
        source = self.source(audit_receipt).encode()
        return _publish_bytes(destination,source)

    def render(self, audit_receipt, destination, *, timeout=120, quality='low'):
        if quality not in {'low','medium','high'}:
            raise ValueError('quality must be low, medium or high')
        try:
            manim_version = version('manim')
        except PackageNotFoundError as error:
            raise ImportError('Install nablamath[animation] and Manim system dependencies') from error
        destination = Path(destination)
        if destination.exists():
            raise FileExistsError(destination)
        source = self.source(audit_receipt)
        with tempfile.TemporaryDirectory(prefix='nabla-manim-') as directory:
            root = Path(directory); script = root/'scene.py'
            script.write_text(source,encoding='utf-8')
            option = {'low':'-ql','medium':'-qm','high':'-qh'}[quality]
            run_renderer([sys.executable,'-m','manim','--renderer','cairo',option,'--format','mp4',
                          '--disable_caching','--media_dir',str(root/'media'),
                          '--output_file','nabla.mp4',str(script),'NablaAnimation'],cwd=root,timeout=timeout)
            videos = [path for path in (root/'media').rglob('nabla.mp4') if 'partial_movie_files' not in path.parts]
            if len(videos) != 1:
                raise RuntimeError('Manim did not generate exactly one final MP4')
            data = videos[0].read_bytes()
            if len(data) < 12 or data[4:8] != b'ftyp' or len(data) > 256*1024*1024:
                raise RuntimeError('Invalid or excessive MP4 output')
            _publish_bytes(destination,data)
        record = receipt('manim.render',{'receipt_id':audit_receipt['content_id']},
                         {'video_sha256':hashlib.sha256(data).hexdigest(),
                          'script_sha256':hashlib.sha256(source.encode()).hexdigest()},backend='manim',
                         metadata={'version':manim_version,'quality':quality,'duration':self.duration},
                         parents=[audit_receipt['content_id']])
        return {'path':destination,'receipt':record}
