@dataclass
class Mesh:
    vertices: Array
    faces: Array
    colors: Array
    normals: Optional[Array] = None
    scalar: Optional[Array] = None
    name: str = "mesh"

    def __post_init__(self) -> None:
        self.vertices = np.asarray(self.vertices, dtype=np.float64)
        self.faces = np.asarray(self.faces, dtype=np.int32)
        self.colors = np.asarray(self.colors, dtype=np.float64)
        if self.normals is None:
            self.normals = self.compute_normals()
        if self.scalar is not None:
            self.scalar = np.asarray(self.scalar, dtype=np.float64)

    def compute_normals(self) -> Array:
        v, f = self.vertices, self.faces
        fn = np.cross(v[f[:, 1]] - v[f[:, 0]], v[f[:, 2]] - v[f[:, 0]])
        fn = normalize(fn)
        vn = np.zeros_like(v)
        for i, tri in enumerate(f):
            vn[tri] += fn[i]
        return normalize(vn)

    def bounds(self) -> Tuple[Array, Array]:
        return self.vertices.min(axis=0), self.vertices.max(axis=0)


@dataclass
class MeshletStats:
    face_count: int
    vertex_count: int
    meshlet_count: int
    lod_levels: int
    average_faces_per_meshlet: float
    approximate_memory_mb: float


def compute_meshlet_stats(mesh: Mesh, faces_per_meshlet: int = 64, lod_levels: int = 5) -> MeshletStats:
    face_count = len(mesh.faces)
    meshlets = math.ceil(face_count / max(1, faces_per_meshlet))
    memory = (mesh.vertices.nbytes + mesh.faces.nbytes + mesh.colors.nbytes + mesh.normals.nbytes) / (1024 ** 2)
    return MeshletStats(
        face_count=face_count,
        vertex_count=len(mesh.vertices),
        meshlet_count=meshlets,
        lod_levels=lod_levels,
        average_faces_per_meshlet=face_count / max(meshlets, 1),
        approximate_memory_mb=memory,
    )


@dataclass
class BVHStats:
    primitive_count: int
    estimated_nodes: int
    estimated_depth: int
    sah_description: str


def estimate_bvh_stats(mesh: Mesh) -> BVHStats:
    tris = len(mesh.faces)
    estimated_nodes = max(1, 2 * tris - 1)
    depth = int(math.ceil(math.log2(max(tris, 2))))
    return BVHStats(
        primitive_count=tris,
        estimated_nodes=estimated_nodes,
        estimated_depth=depth,
        sah_description="Median split BVH estimate; production path would use SAH binning and spatial splits.",
    )


