def generate_animation_frames(spec: RocketSpec, material: MaterialSpec, out_dir: Path, frames: int = 48) -> List[Path]:
    """Fast professional-looking 2D cinematic keyframe renderer for MP4 generation.

    The static report figures use 3D Matplotlib; animation uses a fast side-view renderer so the
    single file remains practical on ordinary machines.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    frame_paths: List[Path] = []
    W, H = 1280, 720
    for i in range(frames):
        t = i / max(frames - 1, 1)
        heat = 0.20 + 0.72 * math.sin(math.pi * t) ** 2
        img = Image.new("RGB", (W, H), (5, 10, 18))
        draw = ImageDraw.Draw(img, "RGBA")
        # Star field / atmosphere gradient.
        for y in range(H):
            k = y / H
            r = int(8 + 18 * k)
            g = int(14 + 22 * k)
            b = int(28 + 44 * k)
            draw.line([(0, y), (W, y)], fill=(r, g, b, 255))
        rng = np.random.default_rng(123)
        for _ in range(160):
            x = int(rng.integers(0, W)); y = int(rng.integers(0, H//2)); a = int(rng.integers(40, 140))
            draw.point((x, y), fill=(255, 255, 255, a))
        # Camera pan and rocket body.
        scale = 10.0
        x0 = int(180 + 55 * math.sin(2*math.pi*t))
        yc = H // 2
        L = int(spec.total_length_m * scale)
        R = int(spec.body_radius_m * scale)
        nose = int(spec.nose_length_m * scale)
        tail = int(spec.tail_length_m * scale)
        cyl = L - nose - tail
        hot = np.array(material.plasma_rgb) * 255
        hull = np.array(material.hull_rgb) * 255
        tile = np.array(material.tile_rgb) * 255
        heat_col = tuple(int(v) for v in np.clip(hull*(1-0.55*heat)+hot*(0.55*heat),0,255))
        # Plasma sheath.
        sheath = int(18 + 55 * heat)
        draw.ellipse([x0-sheath, yc-R-sheath, x0+L+sheath, yc+R+sheath], outline=(255,90,25,int(45+80*heat)), width=max(2,int(7*heat)))
        # Body polygon: nose + cylinder + tail.
        poly = [(x0, yc), (x0+nose, yc-R), (x0+nose+cyl, yc-R), (x0+L, yc-int(R*0.35)), (x0+L, yc+int(R*0.35)), (x0+nose+cyl, yc+R), (x0+nose, yc+R)]
        draw.polygon(poly, fill=(*heat_col,255), outline=(240,245,255,190))
        # Ceramic belly.
        draw.polygon([(x0+nose, yc+int(R*.35)), (x0+nose+cyl, yc+int(R*.35)), (x0+L, yc+int(R*.28)), (x0+nose+cyl, yc+R), (x0+nose, yc+R)], fill=(int(tile[0]),int(tile[1]),int(tile[2]),245))
        # Panels.
        for k in range(12):
            px = x0+nose+int(k*cyl/12)
            draw.line([(px,yc-R+4),(px,yc+R-4)], fill=(255,255,255,35), width=1)
        # Fins.
        finx = x0 + nose + int(cyl*0.78)
        draw.polygon([(finx,yc+R-5),(finx+70,yc+R-5),(finx+40,yc+R+62)], fill=(20,22,26,255), outline=(230,230,240,120))
        draw.polygon([(finx,yc-R+5),(finx+70,yc-R+5),(finx+40,yc-R-62)], fill=(20,22,26,255), outline=(230,230,240,120))
        # Engine plume.
        plume_len = int(120 + 80*heat)
        draw.polygon([(x0+L,yc-int(R*.25)),(x0+L+plume_len,yc),(x0+L,yc+int(R*.25))], fill=(255,95,25,int(80+95*heat)))
        draw.polygon([(x0+L,yc-int(R*.12)),(x0+L+int(plume_len*.55),yc),(x0+L,yc+int(R*.12))], fill=(255,220,95,int(120+95*heat)))
        # HUD.
        mode = "BEAUTY" if t < .34 else "THERMAL" if t < .67 else "X-RAY"
        draw.rounded_rectangle([22,22,430,150], radius=14, fill=(0,0,0,145), outline=(120,180,255,100))
        lines = [
            f"NablaRender v0.7 Ultra — {mode}",
            f"frame {i+1:03d}/{frames:03d}",
            f"heat scalar: {heat:.3f}",
            f"rocket length: {spec.total_length_m:.1f} m",
            "single-file generated MP4",
        ]
        yy=38
        for line in lines:
            draw.text((42,yy), line, fill=(230,242,255,240)); yy += 22
        fp = out_dir / f"frame_{i:04d}.png"
        img.save(fp)
        frame_paths.append(fp)
    return frame_paths


def encode_video(frames: Sequence[Path], out_path: Path, fps: int = 12) -> Optional[str]:
    if not frames:
        return None
    out_path.parent.mkdir(parents=True, exist_ok=True)
    ffmpeg = shutil.which("ffmpeg")
    if ffmpeg:
        pattern = str(frames[0].parent / "frame_%04d.png")
        cmd = [ffmpeg, "-y", "-framerate", str(fps), "-i", pattern, "-c:v", "libx264", "-pix_fmt", "yuv420p", str(out_path)]
        proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=180)
        if proc.returncode == 0 and out_path.exists() and out_path.stat().st_size > 0:
            return str(out_path)
    if imageio is not None:
        try:
            with imageio.get_writer(out_path, fps=fps, macro_block_size=1) as writer:
                for fp in frames:
                    writer.append_data(imageio.imread(fp))
            return str(out_path)
        except Exception:
            return None
    return None


