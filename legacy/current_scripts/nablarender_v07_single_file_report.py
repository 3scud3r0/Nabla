def build_rocket_mesh(spec: RocketSpec, material: MaterialSpec, mode: str = "beauty", heat: float = 0.45) -> Mesh:
    n_ax = int(spec.axial_segments)
    n_th = int(spec.circum_segments)
    nose_n = max(12, int(n_ax * spec.nose_length_m / spec.total_length_m))
    cyl_n = max(18, int(n_ax * spec.cylinder_length_m / spec.total_length_m))
    tail_n = max(10, n_ax - nose_n - cyl_n)

    x1 = np.linspace(0.0, spec.nose_length_m, nose_n)
    r1 = spec.body_radius_m * (x1 / max(spec.nose_length_m, 1e-9)) ** 0.72
    x2 = np.linspace(spec.nose_length_m, spec.nose_length_m + spec.cylinder_length_m, cyl_n)
    r2 = np.ones_like(x2) * spec.body_radius_m
    x3 = np.linspace(spec.nose_length_m + spec.cylinder_length_m, spec.total_length_m, tail_n)
    frac = (x3 - x3.min()) / max(x3.max() - x3.min(), 1e-9)
    r3 = spec.body_radius_m - (spec.body_radius_m - spec.engine_exit_radius_m) * frac ** 1.2

    x = np.concatenate([x1, x2, x3])
    radius = np.concatenate([r1, r2, r3])
    theta = np.linspace(0.0, 2.0 * np.pi, n_th, endpoint=False)

    vertices, colors_v, scalar_v = [], [], []
    hull = np.array(material.hull_rgb)
    tile = np.array(material.tile_rgb)
    plasma = np.array(material.plasma_rgb)

    for i, xi in enumerate(x):
        xn = xi / max(spec.total_length_m, 1e-9)
        for tj in theta:
            y, z = radius[i] * math.cos(tj), radius[i] * math.sin(tj)
            vertices.append([xi, y, z])
            belly = 1.0 if (math.sin(tj) < -0.34 and xi > spec.nose_length_m * 0.6) else 0.0
            brushed = 0.87 + 0.13 * math.sin(44 * tj + 19 * xn)
            panel = 0.5 + 0.5 * math.sin(12 * math.pi * xn + 4 * math.sin(tj * 2))
            hot = heat * (math.exp(-4.3 * xn) + 0.62 * belly * math.exp(-0.6 * xn))
            if mode == "beauty":
                base = lerp(hull * brushed, tile, 0.72 * belly)
                col = lerp(base, plasma, clamp01(hot * 0.55))
            elif mode == "thermal":
                col = np.array([min(1.0, hot * 1.4), min(1.0, hot ** 0.62), max(0.02, 1.0 - hot * 0.75)])
            elif mode == "infrared":
                col = np.array([min(1.0, hot * 1.35), min(1.0, hot ** 0.7), 0.02])
            elif mode == "xray":
                rim = abs(math.cos(tj)) ** 0.35
                col = np.array([0.20 + 0.22 * panel, 0.78 + 0.18 * rim, 1.0])
            else:
                col = hull
            colors_v.append(np.clip(col, 0.0, 1.0))
            scalar_v.append(hot)

    faces = []
    for i in range(len(x) - 1):
        for j in range(n_th):
            a = i * n_th + j
            b = i * n_th + (j + 1) % n_th
            c = (i + 1) * n_th + j
            d = (i + 1) * n_th + (j + 1) % n_th
            faces.append([a, c, b])
            faces.append([b, c, d])

    # Fins as triangular prisms, simplified into extra triangles.
    base_vertices = len(vertices)
    for k in range(spec.fin_count):
        phi = 2.0 * math.pi * k / spec.fin_count
        radial = np.array([0.0, math.cos(phi), math.sin(phi)])
        chord = np.array([-1.0, 0.0, 0.0])
        thick_axis = normalize(np.cross(chord, radial))
        root_x = spec.nose_length_m + spec.cylinder_length_m * 0.78
        p0 = np.array([root_x, spec.body_radius_m * math.cos(phi), spec.body_radius_m * math.sin(phi)])
        p1 = p0 + chord * spec.fin_root_chord_m
        p2 = p0 + radial * spec.fin_span_m + chord * (spec.fin_root_chord_m * 0.38)
        p3 = p2 + chord * spec.fin_tip_chord_m
        thk = thick_axis * 0.07
        fin_verts = [p0+thk, p1+thk, p2+thk, p3+thk, p0-thk, p1-thk, p2-thk, p3-thk]
        start = len(vertices)
        vertices.extend([p.tolist() for p in fin_verts])
        fin_col = material.tile_rgb if mode != "xray" else (0.34, 0.93, 1.0)
        colors_v.extend([fin_col] * 8)
        scalar_v.extend([0.4 * heat] * 8)
        faces.extend([
            [start+0, start+1, start+2], [start+1, start+3, start+2],
            [start+4, start+6, start+5], [start+5, start+6, start+7],
            [start+0, start+4, start+1], [start+1, start+4, start+5],
            [start+1, start+5, start+3], [start+3, start+5, start+7],
            [start+3, start+7, start+2], [start+2, start+7, start+6],
            [start+2, start+6, start+0], [start+0, start+6, start+4],
        ])

    return Mesh(
        vertices=np.asarray(vertices, dtype=np.float64),
        faces=np.asarray(faces, dtype=np.int32),
        colors=np.asarray(colors_v, dtype=np.float64),
        scalar=np.asarray(scalar_v, dtype=np.float64),
        name=f"rocket_{mode}",
    )


