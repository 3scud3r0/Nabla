def run_mission_calculations(mission: MissionSpec, spec: RocketSpec) -> Dict[str, Any]:
    earth_mu = 3.986004418e14
    earth_r = 6_371_000.0
    r_orbit = earth_r + mission.orbit_altitude_m
    v_circ = math.sqrt(earth_mu / r_orbit)
    period = 2 * math.pi * math.sqrt(r_orbit**3 / earth_mu)
    frontal_area = math.pi * spec.body_radius_m**2
    ballistic_coeff = 134_000.0 / (1.28 * frontal_area)
    stagnation_pressure = mission.peak_dynamic_pressure_pa * (1.0 + 0.2 * (mission.entry_velocity_m_s / 295.0) ** 2) ** 3.5
    radiative_power_proxy = 0.84 * 5.670374419e-8 * mission.peak_wall_temperature_k**4
    return {
        "earth_mu": earth_mu,
        "earth_radius_m": earth_r,
        "orbit_radius_m": r_orbit,
        "circular_velocity_m_s": v_circ,
        "orbital_period_s": period,
        "frontal_area_m2": frontal_area,
        "ballistic_coefficient_kg_m2": ballistic_coeff,
        "stagnation_pressure_proxy_pa": stagnation_pressure,
        "radiative_power_proxy_w_m2": radiative_power_proxy,
        "plasma_blackout": mission.peak_plasma_frequency_hz > 2.2e9,
    }


