"""Generate and kernel-check a public, stratified rational proof regression corpus.

Thirty thousand propositions instantiate ten structural families. This is an
engineering conformance corpus, not 30,000 algorithms or independent discoveries.
Every success requires the actual Lean compiler and an axiom audit for every
named theorem. Source generation and kernel compilation are separate operations.
"""

from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor
from fractions import Fraction
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tarfile
import time

from nablamath.core.semantic_ir import fingerprint
from nablamath.expression import parse_expr
from nablamath.formal.lean_checker import ALLOWED_AXIOMS, find_lake, run_lean_process
from nablamath.formal.lean_std import std_source
from nablamath.formal.statement import FormalStatement, Predicate


ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT/'lean/Conformance'
FAMILIES = (
    'difference_squares', 'affine_square', 'distributive', 'guarded_inverse',
    'monotone_affine', 'nonnegative_square', 'closed_rational', 'bounded_square',
    'quadratic_minimum', 'fraction_sum',
)
FIRST_LIMIT = 120
SECOND_LIMIT = 25
SHARD_FIRST = 20


def _predicate(left, relation, right):
    return Predicate(parse_expr(left), relation, parse_expr(right))


def proposition(family, first, second):
    """Construct typed statements without accepting Lean snippets or tactics."""
    if family not in FAMILIES or type(first) is not int or type(second) is not int:
        raise ValueError('Unknown proof family or coefficient index')
    if not 1 <= first <= FIRST_LIMIT or not 1 <= second <= SECOND_LIMIT:
        raise ValueError('Coefficient index outside the frozen corpus')
    a = f'({Fraction(first, second)})'
    b = f'({Fraction(26*first+second, 37)})'
    if family == 'difference_squares':
        return FormalStatement.equality(f'({a}*x+{b})*({a}*x-{b})', f'{a}*{a}*x*x-{b}*{b}')
    if family == 'affine_square':
        return FormalStatement.equality(f'({a}*x+{b})**2', f'{a}**2*x*x+2*{a}*{b}*x+{b}**2')
    if family == 'distributive':
        return FormalStatement.equality(f'{a}*(x+{b}*y)', f'{a}*x+{a}*{b}*y')
    if family == 'guarded_inverse':
        return FormalStatement.equality(f'({a}*x+{b})/({a}*x+{b})', '1')
    if family == 'monotone_affine':
        return FormalStatement(_predicate(f'{a}*x+{b}', 'le', f'{a}*y+{b}'),
                               (_predicate('x', 'le', 'y'),))
    if family == 'nonnegative_square':
        return FormalStatement(_predicate(f'({a}*x-{b})**2', 'ge', '0'))
    if family == 'closed_rational':
        expected = Fraction(first, second)+Fraction(26*first+second, 37)
        return FormalStatement.equality(f'{a}+{b}', str(expected))
    if family == 'bounded_square':
        return FormalStatement(_predicate('x*x', 'le', f'{b}**2'),
                               (_predicate('x', 'ge', f'-{b}'), _predicate('x', 'le', b)))
    if family == 'quadratic_minimum':
        return FormalStatement(_predicate(f'{a}*(x-{b})**2+{b}', 'ge', b))
    return FormalStatement.equality(f'{a}/x+{b}/x', f'({a}+{b})/x')


def generated_sources(*, first_limit=FIRST_LIMIT, second_limit=SECOND_LIMIT):
    if (type(first_limit) is not int or type(second_limit) is not int
            or not 1 <= first_limit <= FIRST_LIMIT or not 1 <= second_limit <= SECOND_LIMIT):
        raise ValueError('Invalid frozen corpus dimensions')
    sources = {}
    inventories = {}
    header = ('-- Generated by tools/rational_proof_corpus.py; do not edit manually.\n'
              '-- Public regression instances; no claim of general scientific acceptance.\n'
              'import Std\nset_option autoImplicit false\n'
              'set_option maxHeartbeats 200000\nset_option maxRecDepth 1024\n\n')
    for family in FAMILIES:
        for start in range(1, first_limit+1, SHARD_FIRST):
            part = (start-1)//SHARD_FIRST+1
            label = family if part == 1 else f'{family}_part{part:03d}'
            parts = [header]
            inventory = []
            for first in range(start, min(start+SHARD_FIRST, first_limit+1)):
                for second in range(1, second_limit+1):
                    statement = proposition(family, first, second)
                    name = f'nabla_{family}_{first:02d}_{second:02d}'
                    source = std_source(statement)
                    # Only a compiler-controlled theorem name changes.
                    body = source[source.index('theorem nabla_std_generated'):]
                    parts.append(body.replace('nabla_std_generated', name))
                    inventory.append({'name': name, 'statement_id': statement.content_id})
            sources[label+'.lean'] = ''.join(parts)
            inventories[label] = inventory
    return sources, inventories


def generate(*, check=False, refresh=False):
    sources, inventories = generated_sources()
    protocol = {
        'version': 'rational-kernel-conformance-v2',
        'families': list(FAMILIES), 'coefficient_indices': [FIRST_LIMIT, SECOND_LIMIT],
        'max_theorems_per_shard': SHARD_FIRST*SECOND_LIMIT,
        'theorems': sum(len(rows) for rows in inventories.values()),
        'selection': 'Frozen public Cartesian corpus; no tuning, holdout or learned model',
        'instances': inventories,
        'sources': {name: hashlib.sha256(source.encode()).hexdigest() for name, source in sources.items()},
        'scope': 'Ten structural families of rational propositions, not thousands of mathematical capabilities',
    }
    sources['manifest.json'] = json.dumps({**protocol, 'protocol_id': fingerprint(protocol)}, indent=2, sort_keys=True)+'\n'
    if refresh:
        previous = json.loads((DESTINATION/'manifest.json').read_text())
        names = set(previous['sources']) | {'manifest.json'}
        if {path.name for path in DESTINATION.iterdir()} != names:
            raise ValueError('Cannot refresh a corpus with unknown additional files')
        for name, digest in previous['sources'].items():
            if hashlib.sha256((DESTINATION/name).read_bytes()).hexdigest() != digest:
                raise ValueError('Refusing to replace a manually edited corpus source: '+name)
        archive = ROOT/'.nabla/proof-corpus-history'/f'{time.time_ns()}.tar.gz'
        archive.parent.mkdir(parents=True, exist_ok=True)
        with tarfile.open(archive, 'x:gz') as handle:
            for name in sorted(names):
                handle.add(DESTINATION/name, arcname=name)
        with tarfile.open(archive, 'r:gz') as handle:
            for name in names:
                if handle.extractfile(name).read() != (DESTINATION/name).read_bytes():
                    raise ValueError('Prior corpus archive verification failed')
    if check:
        for name, source in sources.items():
            path = DESTINATION/name
            if not path.is_file() or path.read_text(encoding='utf-8') != source:
                raise ValueError('Missing or changed generated corpus file: '+name)
        actual = {path.name for path in DESTINATION.iterdir() if path.is_file()}
        if actual != set(sources):
            raise ValueError('Unexpected files in generated corpus directory')
    else:
        DESTINATION.mkdir(exist_ok=True)
        for name, source in sources.items():
            path = DESTINATION/name
            if path.exists() and path.read_text(encoding='utf-8') != source and not refresh:
                raise ValueError('Refusing to overwrite a differing corpus file: '+name)
            if not path.exists() or refresh:
                path.write_text(source, encoding='utf-8')
    return json.loads(sources['manifest.json'])


def verify(output, *, workers=3, timeout=180):
    manifest = generate(check=True)
    output = Path(output)
    output.mkdir(parents=True, exist_ok=False)
    if type(workers) is not int or not 1 <= workers <= 4:
        raise ValueError('Kernel worker count must be in [1,4]')
    lake = find_lake(ROOT/'lean')
    if lake is None:
        raise ValueError('Pinned Lean compiler is unavailable')
    lean = lake.with_name('lean')
    environment = dict(os.environ)
    environment.pop('LEAN_PATH', None)
    environment.pop('LEAN_SRC_PATH', None)
    version = run_lean_process([str(lean), '--version'], cwd=ROOT, env=environment, timeout=20)
    pin = (ROOT/'lean/lean-toolchain').read_text().strip().rsplit('v', 1)[-1]
    if version.returncode or not re.search(r'Lean \(version '+re.escape(pin)+r'(?:,|\))', version.stdout):
        raise ValueError('Compiler does not match the project pin')

    def compile_family(family):
        started = time.perf_counter()
        path = DESTINATION/(family+'.lean')
        try:
            completed = run_lean_process([str(lean), str(path)], cwd=output,
                                         env=environment, timeout=timeout)
            text = completed.stdout+'\n'+completed.stderr
            names = re.findall(r"'([^']+)' (?:depends on axioms:|does not depend on any axioms)", text)
            expected = [row['name'] for row in manifest['instances'][family]]
            groups = re.findall(r'depends on axioms:\s*\[([^\]]*)\]', text)
            axioms = sorted({name.strip() for group in groups for name in group.split(',') if name.strip()})
            accepted = (completed.returncode == 0 and names == expected and 'sorry' not in text
                        and not set(axioms)-ALLOWED_AXIOMS)
            result = {'family': family, 'status': 'passed' if accepted else 'failed',
                      'returncode': completed.returncode, 'expected_theorems': len(expected),
                      'audited_theorems': len(names), 'axioms': axioms}
        except subprocess.TimeoutExpired:
            text = 'Kernel compilation timed out; no proofs accepted for this family.\n'
            result = {'family': family, 'status': 'timeout', 'expected_theorems': len(manifest['instances'][family]),
                      'audited_theorems': 0, 'returncode': None}
        log = output/(family+'.log')
        log.write_text(text, encoding='utf-8')
        print(json.dumps({'shard': family, 'status': result['status'],
                          'audited_theorems': result['audited_theorems']}), flush=True)
        return {**result, 'seconds': time.perf_counter()-started,
                'log_sha256': hashlib.sha256(log.read_bytes()).hexdigest()}

    with ThreadPoolExecutor(max_workers=workers) as executor:
        results = list(executor.map(compile_family, manifest['instances']))
    passed = sum(row['expected_theorems'] for row in results if row['status'] == 'passed')
    report = {'profile': manifest['version'], 'protocol_id': manifest['protocol_id'],
              'tool_version': version.stdout.strip(), 'families': results,
              'expected_theorems': manifest['theorems'], 'accepted_theorems': passed,
              'all_passed': passed == manifest['theorems'],
              'private_holdout': False, 'external_review_performed': False}
    report = {**report, 'report_id': fingerprint(report)}
    (output/'report.json').write_text(json.dumps(report, indent=2, sort_keys=True)+'\n')
    return report


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--refresh', action='store_true', help='Archive intact generated sources before regenerating')
    parser.add_argument('--verify', type=Path, help='Fresh output directory for kernel evidence')
    parser.add_argument('--workers', type=int, default=3)
    args = parser.parse_args(argv)
    if args.verify:
        report = verify(args.verify.resolve(), workers=args.workers)
        print(json.dumps({'accepted_theorems': report['accepted_theorems'],
                          'expected_theorems': report['expected_theorems'], 'all_passed': report['all_passed']}))
        return 0 if report['all_passed'] else 1
    if args.check and args.refresh:
        parser.error('--check and --refresh are mutually exclusive')
    manifest = generate(check=args.check, refresh=args.refresh)
    print(json.dumps({'theorems': manifest['theorems'], 'protocol_id': manifest['protocol_id']}))
    return 0


if __name__ == '__main__':
    sys.exit(main())
